def counts(rules):
    by_group = Counter(r["rule_group"] for r in rules)
    by_status = Counter(r["approval_status"] for r in rules)
    by_mvp = Counter(r["mvp_status"] for r in rules)
    by_effect = Counter(r["decision_effect"]["on_fail"] for r in rules)
    return by_group, by_status, by_mvp, by_effect


