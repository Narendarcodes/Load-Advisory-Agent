"""Generate infra/langfuse/.env with strong local secrets.

The Langfuse stack reads this file; the agent can consume the same values by
exporting the LANGFUSE_* lines. The file is git-ignored and never printed by
this script. Re-running refuses to overwrite an existing .env unless --force,
because replacing credentials would orphan the already-initialised database.

Usage:
    python infra/langfuse/generate_env.py [--out PATH] [--force]
"""
from __future__ import annotations

import argparse
import secrets
import sys
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parent / ".env"


def _hex(nbytes: int) -> str:
    return secrets.token_hex(nbytes)


def render() -> str:
    pg_user, pg_db = "langfuse", "langfuse"
    pg_password = _hex(24)
    public_key = "pk-lf-" + _hex(16)
    secret_key = "sk-lf-" + _hex(32)
    lines = [
        "# Generated by infra/langfuse/generate_env.py — local secrets, never commit.",
        "# Stack services read the variables above the marker; the agent reads the LANGFUSE_* ones below.",
        "NEXTAUTH_URL=http://127.0.0.1:3000",
        f"NEXTAUTH_SECRET={_hex(32)}",
        f"SALT={_hex(32)}",
        f"ENCRYPTION_KEY={_hex(32)}",
        "",
        f"POSTGRES_USER={pg_user}",
        f"POSTGRES_PASSWORD={pg_password}",
        f"POSTGRES_DB={pg_db}",
        f"DATABASE_URL=postgresql://{pg_user}:{pg_password}@postgres:5432/{pg_db}",
        "",
        "CLICKHOUSE_USER=clickhouse",
        f"CLICKHOUSE_PASSWORD={_hex(24)}",
        "",
        f"REDIS_AUTH={_hex(24)}",
        "",
        f"MINIO_ROOT_USER={_hex(12)}",
        f"MINIO_ROOT_PASSWORD={_hex(24)}",
        "",
        "# First-start bootstrap (ignored once the database exists).",
        "LANGFUSE_INIT_ORG_ID=loan-advisory",
        'LANGFUSE_INIT_ORG_NAME="Load Advisory Agent (local)"',
        "LANGFUSE_INIT_PROJECT_ID=loan-advisory-local",
        "LANGFUSE_INIT_PROJECT_NAME=loan-advisory-local",
        f"LANGFUSE_INIT_PROJECT_PUBLIC_KEY={public_key}",
        f"LANGFUSE_INIT_PROJECT_SECRET_KEY={secret_key}",
        "LANGFUSE_INIT_USER_EMAIL=admin@loan-advisory.local",
        "LANGFUSE_INIT_USER_NAME=Local Admin",
        f"LANGFUSE_INIT_USER_PASSWORD={_hex(16)}",
        "",
        "# Agent side: export these into the process that serves/evals the advisory agent.",
        f"LANGFUSE_PUBLIC_KEY={public_key}",
        f"LANGFUSE_SECRET_KEY={secret_key}",
        "LANGFUSE_BASE_URL=http://127.0.0.1:3000",
        "LANGFUSE_ENVIRONMENT=local",
        "LANGFUSE_ENABLED=1",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = ap.parse_args(argv)
    out: Path = args.out
    if out.exists() and not args.force:
        print(f"refusing to overwrite {out} (use --force to replace existing credentials)", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    try:
        out.chmod(0o600)
    except OSError:
        pass
    print(f"wrote {out} (git-ignored); dashboard http://127.0.0.1:3000")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
